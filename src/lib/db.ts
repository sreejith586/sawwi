export type Params = (string | number | boolean | null)[];
export type Row = Record<string, string | number | boolean | null>;

/** The store modules' view of the database. Placeholders are `?`, as before; they're numbered for Postgres here. */
export interface Db {
  all<T = Row>(sql: string, ...params: Params): Promise<T[]>;
  get<T = Row>(sql: string, ...params: Params): Promise<T | undefined>;
  /** Runs a statement; `changes` is the number of rows it inserted, updated or deleted. */
  run(sql: string, ...params: Params): Promise<{ changes: number }>;
  /** Runs `fn` in one transaction: committed if it resolves, rolled back if it throws. */
  tx<T>(fn: (db: Db) => Promise<T>): Promise<T>;
}

const numbered = new Map<string, string>();
/** `?` → `$1`, `$2`, … outside quoted strings and identifiers. */
export function toPositional(sql: string): string {
  const hit = numbered.get(sql);
  if (hit !== undefined) return hit;
  let out = "";
  let n = 0;
  let quote: string | null = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else out += ch === "?" ? `$${++n}` : ch;
  }
  numbered.set(sql, out);
  return out;
}

// COUNT(*) and SUM() come back as int8/numeric; every number here fits a JS number.
const INT8 = 20;
const NUMERIC = 1700;

type Driver = {
  query(sql: string, params: Params): Promise<{ rows: Row[]; changes: number }>;
  exec(sql: string): Promise<void>;
  tx<T>(fn: (d: Driver) => Promise<T>): Promise<T>;
};

function pgliteDriver(q: PGlite | Transaction): Driver {
  return {
    async query(sql, params) {
      const r = await q.query<Row>(sql, params);
      return { rows: r.rows, changes: r.affectedRows ?? 0 };
    },
    async exec(sql) {
      await q.exec(sql);
    },
    tx: (fn) => ("transaction" in q ? q.transaction((t) => fn(pgliteDriver(t))) : fn(pgliteDriver(q))),
  };
}

function pgDriver(pool: Pool, client?: PoolClient): Driver {
  const q = client ?? pool;
  return {
    async query(sql, params) {
      const r = await q.query(sql, params);
      return { rows: r.rows as Row[], changes: r.rowCount ?? 0 };
    },
    async exec(sql) {
      await q.query(sql);
    },
    async tx(fn) {
      if (client) return fn(pgDriver(pool, client));
      const c = await pool.connect();
      try {
        await c.query("BEGIN");
        const out = await fn(pgDriver(pool, c));
        await c.query("COMMIT");
        return out;
      } catch (error) {
        await c.query("ROLLBACK");
        throw error;
      } finally {
        c.release();
      }
    },
  };
}

/**
 * The Neon connection string. Vercel's Neon integration names it DATABASE_URL, or
 * SAWWI_DATABASE_URL when the integration was given the "SAWWI" variable prefix (as in production).
 */
export function databaseUrl(): string | undefined {
  return process.env.DATABASE_URL || process.env.SAWWI_DATABASE_URL || undefined;
}

async function open(): Promise<Driver> {
  const url = databaseUrl();
  if (url) {
    const { default: pg } = await import("pg");
    pg.types.setTypeParser(INT8, Number);
    pg.types.setTypeParser(NUMERIC, Number);
    // Neon's URLs say sslmode=require, which pg already treats as verify-full (and warns about on
    // every cold start). Say verify-full outright: Neon's certificates are publicly trusted.
    const connectionString = url.replace(/([?&]sslmode=)(prefer|require|verify-ca)\b/, "$1verify-full");
    const pool = new pg.Pool({ connectionString, max: Number(process.env.SAWWI_DB_POOL ?? 5) });
    if (process.env.VERCEL) {
      // Fluid compute reuses warm instances: close idle connections before one is suspended.
      const { attachDatabasePool } = await import("@vercel/functions");
      attachDatabasePool(pool);
    }
    return pgDriver(pool);
  }
  // A deploy without DATABASE_URL would keep its data on a disk that disappears: refuse.
  if (process.env.VERCEL) throw new Error("DATABASE_URL (or SAWWI_DATABASE_URL) is not set. Add the Neon database to this Vercel project (docs/DEPLOY.md).");
  const { PGlite } = await import("@electric-sql/pglite");
  const parsers = { [INT8]: Number, [NUMERIC]: Number };
  // Tests get a fresh in-memory database per test file; development keeps one under .data/.
  if (process.env.VITEST) return pgliteDriver(new PGlite({ parsers }));
  const dir = path.join(dataDir(), "pglite");
  mkdirSync(dir, { recursive: true });
  return pgliteDriver(new PGlite(dir, { parsers }));
}

async function migrate(d: Driver) {
  await d.exec("CREATE TABLE IF NOT EXISTS schema_migrations (id INTEGER PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL)");
  await d.tx(async (t) => {
    // Several cold-starting instances may migrate at once; one does the work, the others wait for it.
    await t.query("SELECT pg_advisory_xact_lock(7370)", []);
    const done = new Set((await t.query("SELECT id FROM schema_migrations", [])).rows.map((r) => Number(r.id)));
    for (const m of MIGRATIONS) {
      if (done.has(m.id)) continue;
      await t.exec(m.sql);
      await t.query("INSERT INTO schema_migrations (id, name, applied_at) VALUES ($1, $2, $3)", [m.id, m.name, new Date().toISOString()]);
    }
  });
}

function facade(driver: () => Promise<Driver>): Db {
  return {
    async all<T>(sql: string, ...params: Params) {
      return (await (await driver()).query(toPositional(sql), params)).rows as T[];
    },
    async get<T>(sql: string, ...params: Params) {
      return (await (await driver()).query(toPositional(sql), params)).rows[0] as T | undefined;
    },
    async run(sql: string, ...params: Params) {
      return { changes: (await (await driver()).query(toPositional(sql), params)).changes };
    },
    async tx<T>(fn: (db: Db) => Promise<T>) {
      return (await driver()).tx((t) => fn(facade(async () => t)));
    },
  };
}

// One database per process, kept on globalThis: dev hot reloads and separately bundled server
// layers re-evaluate this module, and a second PGlite on the same folder would corrupt it.
// Tests keep it per module instead, so each test file gets its own in-memory database.
const g = (process.env.VITEST ? {} : globalThis) as { __sawwiDb?: Promise<Driver> };

function driver(): Promise<Driver> {
  if (!g.__sawwiDb) {
    const opening = open().then(async (d) => {
      await migrate(d);
      return d;
    });
    g.__sawwiDb = opening;
    // A failed open (e.g. the database was unreachable) is retried on the next query.
    opening.catch(() => {
      if (g.__sawwiDb === opening) g.__sawwiDb = undefined;
    });
  }
  return g.__sawwiDb;
}

const db = facade(driver);

/** The database, opened and migrated on first use. */
export function getDb(): Db {
  return db;
}
